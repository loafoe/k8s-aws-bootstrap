#!/usr/bin/env bash
# Prints every OCI image the bootstrap charts pull, so it can be pre-cached
# (airgap mirror, warm ECR pull-through, registry allow-list, ...).
#
# No cluster and no AWS account are involved: the charts are pinned in git and
# rendered here the way ArgoCD renders them. Two reference kinds are collected
# besides the obvious `image:`:
#
#   package:  Crossplane Provider/Function OCI artifacts. Crossplane pulls those
#             itself, so they never appear as a kubelet image and are the classic
#             thing an image-only list misses.
#
#   oci://    Applications in charts/bootstrap that point at a chart registry
#             rather than a path here (common-bootstrap, crossplane-providers,
#             crossplane-functions). Rendered at their pinned tag with the values
#             the Application CR passes, because those values change the set.
#
# Usage:
#   ./scripts/generate-images.sh > images.lock
#
# scripts/check-images-lock.sh (run in CI) fails when the chart/version bumps
# that Renovate makes change the image set without images.lock following.
#
# The cluster half — K3s's own system images plus the charts master userdata
# applies before ArgoCD exists — is generated by scripts/generate-images.sh in
# loafoe/k3s-on-ec2. Union of the two:
#
#   cat k8s-aws-bootstrap/images.lock ../k3s-on-ec2/images.lock \
#     | grep -v '^#' | sort -u
set -Eeuo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"

for tool in helm yq; do
    command -v "$tool" >/dev/null 2>&1 || {
        echo "error: $tool is required (brew install $tool)" >&2
        exit 1
    }
done

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# Charts under charts/ that refuse to render without a cluster identity. These
# only feed the fallback render; the real values come from the Application CRs.
CHART_FALLBACK_ARGS=(
    --set prometheus.serviceMonitor.trustCRDsExist=true
    --set cilium.prometheus.serviceMonitor.trustCRDsExist=true
    --set karpenter.settings.clusterName=preload
    --set aws-load-balancer-controller.clusterName=preload
)

# Prints image: and package: references out of a rendered manifest stream.
# Helm test hooks are skipped: nothing here runs `helm test`, and they only
# contribute test-runner images (bats, kubekins-e2e) to the list.
extract_refs() {
    awk '
        function is_test_hook(   i, n, lines) {
            n = split(block, lines, "\n")
            for (i = 1; i <= n; i++)
                if (lines[i] ~ /helm\.sh\/hook/ && lines[i] ~ /test/) return 1
            return 0
        }
        function emit(v) {
            gsub(/^[[:space:]]+|[[:space:]]+$/, "", v)
            gsub(/^["\047]|["\047]$/, "", v)
            # {{ ... }}: CEL/Go templates rather than literal references. The ECR
            # pull-through rewrite policy in charts/bootstrap looks like this.
            if (v == "" || v ~ /{{/) return
            print v
        }
        function flush(   i, n, lines, v) {
            if (!is_test_hook()) {
                n = split(block, lines, "\n")
                for (i = 1; i <= n; i++) {
                    if (lines[i] !~ /^[[:space:]]*-?[[:space:]]*(image|package):[[:space:]]+/) continue
                    v = lines[i]
                    sub(/^[[:space:]]*-?[[:space:]]*(image|package):[[:space:]]+/, "", v)
                    emit(v)
                }
            }
            block = ""
        }
        /^---[[:space:]]*$/ { flush(); next }
        { block = block $0 "\n" }
        END { flush() }
    '
}

# tag_refs <tag> — prefix each stdin line with a tab-separated provenance tag.
tag_refs() { awk -v tag="$1" 'BEGIN { OFS = "\t" } { print tag, $0 }'; }

render() { # render <chart> [args...]
    local chart="$1"
    shift
    helm template preload "$chart" "$@" 2>"$TMP/helm.err" || {
        echo "error: cannot render $chart" >&2
        cat "$TMP/helm.err" >&2
        return 1
    }
}

# --- the bootstrap chart itself ----------------------------------------------
# Values charts/bootstrap validates as required before it renders anything. The
# list is read out of the chart's own helper so it cannot drift, and every value
# is a placeholder: only the image set matters here. Without them
# `helm template charts/bootstrap` fails at validate.yaml and no Application CR
# is emitted at all.
mapfile -t BOOTSTRAP_ARGS < <(
    grep -oE '\(dict "path" "[^"]+"' charts/bootstrap/templates/_helpers.tpl |
        sed -E 's/.*"path" "([^"]+)"/\1/' | sort -u |
        while read -r path; do
            [ -n "$path" ] && printf '%s\n%s\n' "--set-string" "${path}=preload"
        done
    # owner/managedBy are not validated but do end up in the label maps the
    # Applications pass down. Left empty, 'deploymentLabels:' renders as null and
    # the argo-cd subchart dies on deepCopy, so give them a value.
    printf '%s\n' --set-string environmentConfig.owner=preload \
        --set-string environmentConfig.managedBy=preload
    # Values spliced unquoted into the hsp-addons JSON are JSON themselves (subnet ID lists,
    # security group lists): stub them with a JSON string, or the hsp-addons EnvironmentConfig's
    # JSON check fails the render. Read from the template, like the list above
    grep -oE '": \{\{ \.Values\.[A-Za-z.]+ \}\}' charts/bootstrap/templates/hsp-aws-platform/hsp-addons/_hsp-addons.tpl |
        sed -E 's/.*\.Values\.([A-Za-z.]+) .*/\1/' | sort -u |
        while read -r path; do
            printf '%s\n%s\n' "--set-string" "${path}=\"preload\""
        done
)

bootstrap_manifest() { # bootstrap_manifest [extra args...]
    render charts/bootstrap "${BOOTSTRAP_ARGS[@]}" "$@"
}

bootstrap_manifest >"$TMP/bootstrap.yaml" || exit 1

# The shutdown job's image is a value and only renders when the feature is on, so
# ask for it explicitly: clusters do enable shutdown, and that image has to be
# cached *before* someone flips the flag on an airgapped cluster.
shutdown_image="$(yq -r '.features.shutdown.image // ""' charts/bootstrap/values.yaml)"
if [ -n "$shutdown_image" ] && [ "$shutdown_image" != "null" ]; then
    bootstrap_manifest --set features.shutdown.enabled=true \
        --set-string "features.shutdown.image=$shutdown_image" >"$TMP/bootstrap-shutdown.yaml" ||
        echo "warning: could not render charts/bootstrap with shutdown enabled" >&2
else
    : >"$TMP/bootstrap-shutdown.yaml"
fi

# --- Application CRs ---------------------------------------------------------
# One file per Application, so the rest of the script reads single-document
# files: `yq` glues the results of a multi-document expression (eval-all, -r,
# to make matters worse) onto one line, which is not worth fighting.
mkdir -p "$TMP/apps"
awk -v dir="$TMP/apps" '
    function flush() {
        if (index("\n" buf, "\nkind: Application\n") > 0) {
            file = sprintf("%s/app-%03d.yaml", dir, n++)
            printf "%s", buf > file
            close(file)
        }
        buf = ""
    }
    /^---[[:space:]]*$/ { flush(); next }
    { buf = buf $0 "\n" }
    END { flush() }
' "$TMP/bootstrap.yaml"

# name<TAB>repoURL<TAB>targetRevision<TAB>path, one record per Application, plus
# the values file holding what that Application actually passes.
: >"$TMP/apps.tsv"
for app in "$TMP"/apps/app-*.yaml; do
    name="$(yq -r '.metadata.name' "$app")"
    yq -r '[.metadata.name, (.spec.source.repoURL // ""), (.spec.source.targetRevision // ""),
        (.spec.source.path // "")] | join("\t")' "$app" >>"$TMP/apps.tsv"
    yq '.spec.source.helm.valuesObject // {}' "$app" >"$TMP/values-$name.yaml"
done

# values_for_chart <chart path> -> path to that chart's Application values, or
# non-zero when no Application in the bootstrap app points at it.
values_for_chart() {
    local want="$1" name _repo _version path
    while IFS=$'\t' read -r name _repo _version path; do
        if [ "$path" = "$want" ]; then
            echo "$TMP/values-$name.yaml"
            return 0
        fi
    done <"$TMP/apps.tsv"
    return 1
}

# --- charts/* ----------------------------------------------------------------
# Every vendored chart is rendered twice where possible: once with the app's
# values (what actually runs) and once with chart defaults plus stubs (a superset
# for everything the Application leaves at default). The union is deliberate —
# pre-caching an image nothing pulls costs disk, missing one stalls a bootstrap.
render_local_charts() { # render_local_charts <outfile>
    local out="$1" chart name values
    : >"$out"
    for chart in $(find charts -mindepth 1 -maxdepth 1 -type d ! -name bootstrap | sort); do
        name="$(basename "$chart")"
        {
            if values="$(values_for_chart "$chart")"; then
                if ! render "$chart" --values "$values" "${CHART_FALLBACK_ARGS[@]}" |
                    extract_refs | tag_refs "$name"; then
                    echo "warning: $name: Application values did not render" >&2
                fi
            fi
            if ! render "$chart" "${CHART_FALLBACK_ARGS[@]}" | extract_refs | tag_refs "$name"; then
                echo "warning: $name: default values did not render" >&2
            fi
        } >>"$out"
    done
}

# --- oci:// Applications -----------------------------------------------------
render_oci_charts() { # render_oci_charts <outfile>
    local out="$1" name repo version path
    : >"$out"
    while IFS=$'\t' read -r name repo version path; do
        [ -n "$repo" ] || continue
        case "$repo" in
        oci://*)
            if ! helm template preload "$repo" --version "$version" \
                --values "$TMP/values-$name.yaml" 2>"$TMP/helm.err" |
                extract_refs | tag_refs "$name" >>"$out"; then
                echo "warning: could not render $repo $version ($name)" >&2
                cat "$TMP/helm.err" >&2
            fi
            ;;
        esac
    done <"$TMP/apps.tsv"
}

render_local_charts "$TMP/local.tsv"
render_oci_charts "$TMP/oci.tsv"

# --- output ------------------------------------------------------------------
declare -A seen=()

# emit <section> <name<TAB>ref file> — deduplicated across sections, first
# occurrence wins: a ref cached twice is not more cached, and one flat set is
# what a mirror wants. Takes a file rather than stdin on purpose: a pipeline
# would run this in a subshell and `seen` would not survive the section.
emit() {
    local section="$1" file="$2"
    local -a unique=()
    local _name ref
    while IFS=$'\t' read -r _name ref; do
        [ -n "$ref" ] || continue
        [ -n "${seen[$ref]:-}" ] && continue
        seen[$ref]=1
        unique+=("$ref")
        # A reference with neither tag nor digest resolves to :latest, which is
        # untrustworthy to cache: say so rather than let it look pinned.
        case "$ref" in
        *@sha256:*) ;;
        *)
            case "${ref##*/}" in
            *:*) ;;
            *) echo "warning: $ref has no tag or digest (implicit :latest)" >&2 ;;
            esac
            ;;
        esac
    done < <(sort -u "$file")
    [ ${#unique[@]} -gt 0 ] || return 0
    printf '# --- %s\n' "$section"
    printf '%s\n' "${unique[@]}"
}

echo "# Generated by scripts/generate-images.sh from the pins in git. Do not edit."
echo "# One OCI reference per line under a '# --- <source>' header."
echo "# Read it back with: grep -v '^#' images.lock | sort -u"
echo

# Images the bootstrap chart inlines itself (jobs, shutdown) — no app CR owns them.
cat "$TMP/bootstrap.yaml" "$TMP/bootstrap-shutdown.yaml" |
    extract_refs | tag_refs "charts/bootstrap" >"$TMP/section.tsv"
emit "charts/bootstrap (jobs + shutdown)" "$TMP/section.tsv"

mapfile -t LOCAL_CHARTS < <(cut -f1 "$TMP/local.tsv" | sort -u)
for chart in "${LOCAL_CHARTS[@]}"; do
    [ -n "$chart" ] || continue
    awk -F'\t' -v c="$chart" '$1 == c' "$TMP/local.tsv" >"$TMP/section.tsv"
    emit "charts/$chart" "$TMP/section.tsv"
done

mapfile -t OCI_APPS < <(cut -f1 "$TMP/oci.tsv" | sort -u)
for app in "${OCI_APPS[@]}"; do
    [ -n "$app" ] || continue
    awk -F'\t' -v a="$app" '$1 == a' "$TMP/oci.tsv" >"$TMP/section.tsv"
    emit "app $app" "$TMP/section.tsv"
done

if [ ${#seen[@]} -eq 0 ]; then
    echo "error: no images resolved — did the charts move?" >&2
    exit 1
fi
