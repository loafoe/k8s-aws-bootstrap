#!/usr/bin/env bash
set -euo pipefail

# restrict-wildcard-rbac and restrict-escalation-verbs read the Argo CD
# exemption lists from charts/bootstrap/values.yaml via Helm templating
# (see charts/bootstrap/templates/_helpers.tpl:
# bootstrap.argoCDRbacExemptionMatchCondition), so the committed source
# under charts/bootstrap/templates/kyverno/ is not valid standalone YAML and
# the `kyverno` CLI cannot load it directly. This script renders both
# policies with the chart's default values and writes the result into
# tests/policies/rbac-argocd-exemption/rendered-policies/, which is what
# that suite's kyverno-test.yaml actually exercises.
#
# Re-run this and commit the result whenever values.yaml's
# features.kyverno.rbacExemptions block, or either policy template,
# changes - otherwise the fixture silently drifts from the deployed policy.
#
# Usage: ./scripts/render-rbac-exemption-test-fixtures.sh

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"

OUT_DIR="tests/policies/rbac-argocd-exemption/rendered-policies"
mkdir -p "$OUT_DIR"

# Dummy values for the fields charts/bootstrap/templates/_helpers.tpl
# requires non-empty; irrelevant to the RBAC policies rendered here.
HELM_SET_ARGS=(
  --set features.hspAwsPlatform.enabled=false
  --set environmentConfig.bootstrap.resourcePrefix=test
  --set environmentConfig.bootstrap.awsAccountId=123456789012
  --set environmentConfig.bootstrap.awsPartition=aws
  --set environmentConfig.bootstrap.awsRegion=eu-west-1
  --set environmentConfig.bootstrap.clusterName=test
  --set environmentConfig.bootstrap.clusterFqdn=test.example.com
  --set environmentConfig.bootstrap.clusterHost=test.example.com
  --set environmentConfig.bootstrap.clusterEndpoint=https://test.example.com
  --set environmentConfig.bootstrap.oidcProvider=oidc.eks.eu-west-1.amazonaws.com/id/TEST
  --set environmentConfig.bootstrap.oidcProviderArn=arn:aws:iam::123456789012:oidc-provider/test
  --set environmentConfig.bootstrap.awsVpcId=vpc-123
  --set environmentConfig.bootstrap.awsLbcRoleArn=arn:aws:iam::123456789012:role/lbc
  --set environmentConfig.bootstrap.awsEbsCsiDriverRoleArn=arn:aws:iam::123456789012:role/ebs
  --set environmentConfig.bootstrap.awsExternalDnsRoleArn=arn:aws:iam::123456789012:role/dns
  --set environmentConfig.bootstrap.certManagerRoleArn=arn:aws:iam::123456789012:role/cm
  --set environmentConfig.bootstrap.karpenterRoleArn=arn:aws:iam::123456789012:role/kp
  --set environmentConfig.bootstrap.crossplaneProviderAwsIamRoleArn=arn:aws:iam::123456789012:role/cp
  --set environmentConfig.bootstrap.karpenterInstanceProfile=test-profile
  --set environmentConfig.bootstrap.k3sTokenParameterName=test
  --set environmentConfig.bootstrap.k3sVersionParameterName=test
)

render() {
  local template="$1" out="$2"
  {
    echo "# GENERATED by ./scripts/render-rbac-exemption-test-fixtures.sh - do not edit by hand."
    echo "# Source: charts/bootstrap/${template}, rendered with chart default values."
    helm template charts/bootstrap "${HELM_SET_ARGS[@]}" --show-only "$template" | tail -n +2
  } > "$out"
}

render templates/kyverno/kyverno-restrict-wildcard-rbac-policy.yaml "$OUT_DIR/kyverno-restrict-wildcard-rbac-policy.yaml"
render templates/kyverno/kyverno-restrict-escalation-verbs-policy.yaml "$OUT_DIR/kyverno-restrict-escalation-verbs-policy.yaml"

echo "Rendered fixtures written to $OUT_DIR/"
